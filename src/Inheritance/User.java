package Inheritance;

public class User {
    private String name;
    private String email;
    private String experience_level;
    private Integer total_xp;
    public String getName() {
        return this.name;
    }
    public void setName(String name) {
        this.name = name;
    }
    public void setEmail(String email) {
        this.email = email;
    }
}
